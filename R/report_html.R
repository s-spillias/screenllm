  paste(
    "body{font-family:-apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;",
    "line-height:1.5;color:#24292f;max-width:52rem;margin:2rem auto;padding:0 1rem;}",
    "h1{font-size:1.6rem;border-bottom:1px solid #d0d7de;padding-bottom:.3rem;}",
    "h2{font-size:1.25rem;margin-top:2rem;border-bottom:1px solid #eaecef;padding-bottom:.2rem;}",
    "nav.toc{background:#f6f8fa;border:1px solid #d0d7de;border-radius:6px;padding:.5rem 1rem;}",
    "nav.toc ul{margin:.3rem 0;padding-left:1.2rem;}",
    "pre{background:#f6f8fa;border-radius:6px;padding:.8rem;overflow-x:auto;",
    "font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;font-size:.85rem;}",
    "table{border-collapse:collapse;width:100%;font-size:.9rem;}",
    "th,td{border:1px solid #d0d7de;padding:.4rem .6rem;text-align:left;vertical-align:top;}",
    "th{background:#f6f8fa;}",
    ".muted{color:#57606a;}",
    ".footer{color:#57606a;font-size:.85rem;}",
    sep = ""
  )
}
